/**
 * Map 1: "island01". A round tropical island (~110 m radius) for 12-16 players.
 * Layout doc: docs/design/levels/island.md
 *
 * Conventions (shared with src/shared/sim and src/render):
 * - Metres, Y up, sea level y = 0. North = -Z, East = +X (yaw 0 looks toward -Z).
 * - Compass angles in this file: 0 deg = north (-Z), 90 deg = east (+X), clockwise.
 * - rotY follows Three.js `rotation.y`: a prop's local +Z axis points toward
 *   (sin rotY, cos rotY) in world XZ. Huts face their door along local +Z. Docks,
 *   boats and driftwood have their long axis along local Z.
 * - Footprints below are conservative layout circles, not sim colliders
 *   (game-developer derives colliders from kind x scale).
 *
 * The layout is generated by a seeded generator (mulberry32) at module load and
 * is fully deterministic. The exported ISLAND is plain IslandMapData (kind 'island', carrier 'seaplane').
 */
import type { IslandMapData } from '../../shared/types';

type Prop = IslandMapData['props'][number];
type PropKind = Prop['kind'];
type LootSpawn = IslandMapData['lootSpawns'][number];
type LootTier = LootSpawn['tier'];
type P2 = { x: number; z: number };

export interface Circle {
  x: number;
  z: number;
  r: number;
}

// ---------------------------------------------------------------------------
// Island shape
// ---------------------------------------------------------------------------
export const ISLAND_RADIUS = 110;
export const WORLD_RADIUS = 135;
export const BASE_HEIGHT = 2.5;
export const BEACH_WIDTH = 18;
/** Coastline radius = islandRadius + amplitude * n(angle), n in [-1, 1]. */
export const SHORE_NOISE = { amplitude: 4, frequency: 2.5, seed: 1107 };

/** Furthest any on-land footprint may reach from the origin: worst-case coastline minus 1 m. */
export const LAND_LIMIT = ISLAND_RADIUS - SHORE_NOISE.amplitude - 1; // 105
/** Worst-case inner edge of the sand band. Anything between this and LAND_LIMIT is always sand. */
export const SAND_INNER = ISLAND_RADIUS - BEACH_WIDTH + SHORE_NOISE.amplitude; // 96

// ---------------------------------------------------------------------------
// Layout rules
// ---------------------------------------------------------------------------
const LAYOUT_SEED = 20261118;
/** Minimum walkable gap between any two prop footprints. */
export const PROP_GAP = 2;
/** Minimum gap between a prop footprint and a player spawn point. */
export const SPAWN_CLEARANCE = 2.5;
/** Minimum gap between a loot point and a prop footprint. */
export const LOOT_PROP_CLEARANCE = 0.75;
/** Minimum spacing between loot points. */
export const LOOT_SPACING = 2.5;

const SPAWN_COUNT = 24;
const SPAWN_START_DEG = 7.5;
const SPAWN_STEP_DEG = 360 / SPAWN_COUNT; // 15 deg, ~26 m apart along the ring
const SPAWN_RING_R = 100;

const INLAND_LOOT = 4;
const INLAND_RARE = 2;

/** Layout footprint radius per kind at scale 1 (bounding radius for multi-circle kinds). */
const FOOT_R: Record<PropKind, number> = {
  palm: 0.45, // trunk 0.3 + lean
  rock: 1.5,
  bush: 0.9,
  crate: 0.75, // 1x1 m, half-diagonal ~0.71
  hut: 2.9, // 4x4 m, half-diagonal ~2.83
  dock: 7.2, // 3x14 m (see propFootprint)
  umbrella: 1.2, // pole + canopy
  boat: 2.0, // 1.5x4 m rowboat (see propFootprint)
  tikiTorch: 0.25,
  driftwood: 1.2, // ~2.4 m log (see propFootprint)
};

// ---------------------------------------------------------------------------
// Points of interest
// ---------------------------------------------------------------------------
interface PoiDef {
  id: string;
  deg: number;
  r: number;
  radius: number;
  loot: { epic: number; rare: number; common: number };
}

/**
 * Loot per POI (docs/design/systems/loot.md: 60-80 spawns total, ~65/25/10 split,
 * epic only at 1-2 contested POIs, >= 4 spawns per POI).
 * Epic goes to the two inland POIs (summit, grove) so no beach spawn has a head start on it.
 */
const POI_DEFS: PoiDef[] = [
  { id: 'summit', deg: 0, r: 0, radius: 22, loot: { epic: 4, rare: 4, common: 1 } },
  { id: 'rocks', deg: 35, r: 90, radius: 16, loot: { epic: 0, rare: 1, common: 3 } },
  { id: 'dock', deg: 95, r: 90, radius: 18, loot: { epic: 0, rare: 4, common: 1 } },
  { id: 'grove', deg: 145, r: 58, radius: 20, loot: { epic: 3, rare: 2, common: 1 } },
  { id: 'tikibar', deg: 195, r: 94, radius: 14, loot: { epic: 0, rare: 1, common: 3 } },
  { id: 'village', deg: 245, r: 78, radius: 22, loot: { epic: 0, rare: 3, common: 2 } },
  { id: 'wreck', deg: 310, r: 92, radius: 16, loot: { epic: 0, rare: 2, common: 2 } },
];

const HILL_DEFS = [
  { name: 'summit', deg: 0, r: 0, radius: 34, height: 10 },
  { name: 'ne-ridge', deg: 50, r: 55, radius: 20, height: 7 },
  { name: 'w-bluff', deg: 285, r: 52, radius: 22, height: 6 },
  { name: 's-knoll', deg: 175, r: 48, radius: 14, height: 4 },
];

/** Candidate final-circle centres (compass deg, distance from origin). All well inland. */
const ZONE_CENTER_DEFS: [number, number][] = [
  [0, 0],
  [30, 40],
  [90, 42],
  [140, 40],
  [200, 40],
  [250, 42],
  [310, 40],
  [355, 36],
];

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
const DEG = Math.PI / 180;
/** Round to cm. The `+ 0` turns -0 into 0. */
const r2 = (v: number): number => Math.round(v * 100) / 100 + 0;
const r3 = (v: number): number => Math.round(v * 1000) / 1000 + 0;
const wrapAngle = (a: number): number => Math.atan2(Math.sin(a), Math.cos(a));
const len = (p: P2): number => Math.hypot(p.x, p.z);
const dist = (a: P2, b: P2): number => Math.hypot(a.x - b.x, a.z - b.z);

/** Compass polar -> XZ (0 deg = north = -Z, 90 deg = east = +X). */
function polar(deg: number, r: number): P2 {
  return { x: r * Math.sin(deg * DEG), z: -r * Math.cos(deg * DEG) };
}

function offset(c: P2, deg: number, r: number): P2 {
  const p = polar(deg, r);
  return { x: c.x + p.x, z: c.z + p.z };
}

/** rotY that points local +Z from `from` toward `to`. */
function facing(from: P2, to: P2): number {
  return Math.atan2(to.x - from.x, to.z - from.z);
}

/** rotY that points local +Z away from the island centre (out to sea). */
function outward(p: P2): number {
  return Math.atan2(p.x, p.z);
}

function poiCentre(id: string): P2 {
  const d = POI_DEFS.find((q) => q.id === id);
  if (!d) throw new Error(`island01: unknown POI ${id}`);
  return polar(d.deg, d.r);
}

function tierList(t: { epic: number; rare: number; common: number }): LootTier[] {
  return [
    ...new Array<LootTier>(t.epic).fill('epic'),
    ...new Array<LootTier>(t.rare).fill('rare'),
    ...new Array<LootTier>(t.common).fill('common'),
  ];
}

function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Conservative layout footprint of a placed prop as one or more circles.
 * Exported for tests and QA tooling.
 */
export function propFootprint(p: Prop): Circle[] {
  const s = p.scale;
  const ax = Math.sin(p.rotY);
  const az = Math.cos(p.rotY);
  const along = (offsets: number[], r: number): Circle[] =>
    offsets.map((o) => ({ x: p.x + ax * o * s, z: p.z + az * o * s, r: r * s }));
  switch (p.kind) {
    case 'dock':
      return along([-5.6, -2.8, 0, 2.8, 5.6], 1.6); // 3 x 14 m deck
    case 'boat':
      return along([-1, 1], 1.0); // 1.5 x 4 m hull
    case 'driftwood':
      return along([-0.6, 0.6], 0.6); // ~2.4 m log
    default:
      return [{ x: p.x, z: p.z, r: FOOT_R[p.kind] * s }];
  }
}

interface Cand {
  kind: PropKind;
  pos: P2;
  rotY: number;
  scale: number;
}

class Builder {
  readonly rng: () => number;
  readonly props: Prop[] = [];
  readonly spawns: P2[] = [];
  readonly loot: LootSpawn[] = [];
  private readonly circles: Circle[] = [];

  constructor(seed: number) {
    this.rng = mulberry32(seed);
  }

  range(min: number, max: number): number {
    return min + (max - min) * this.rng();
  }

  /** Uniform point in a disc. */
  inDisc(c: P2, radius: number): P2 {
    const a = this.rng() * Math.PI * 2;
    const r = radius * Math.sqrt(this.rng());
    return { x: c.x + r * Math.sin(a), z: c.z + r * Math.cos(a) };
  }

  /** Uniform (by area) point in an annulus around the origin. */
  inRing(minR: number, maxR: number): P2 {
    const deg = this.range(0, 360);
    const r = Math.sqrt(this.range(minR * minR, maxR * maxR));
    return polar(deg, r);
  }

  addSpawn(p: P2): void {
    this.spawns.push({ x: r2(p.x), z: r2(p.z) });
  }

  private propFits(p: Prop): boolean {
    for (const c of propFootprint(p)) {
      const outer = len(c) + c.r;
      if (p.kind === 'dock') {
        if (outer > WORLD_RADIUS - 2) return false;
      } else if (outer > LAND_LIMIT) {
        return false;
      }
      for (const o of this.circles) if (dist(c, o) < c.r + o.r + PROP_GAP) return false;
      for (const s of this.spawns) if (dist(c, s) < c.r + SPAWN_CLEARANCE) return false;
      for (const l of this.loot) if (dist(c, l) < c.r + LOOT_PROP_CLEARANCE) return false;
    }
    return true;
  }

  addProp(c: Cand): boolean {
    const p: Prop = {
      kind: c.kind,
      x: r2(c.pos.x),
      z: r2(c.pos.z),
      rotY: r3(wrapAngle(c.rotY)),
      scale: r2(c.scale),
    };
    if (!this.propFits(p)) return false;
    this.props.push(p);
    this.circles.push(...propFootprint(p));
    return true;
  }

  /** Place at `c.pos`, or at the first free jittered spot within `search` metres. */
  propNear(c: Cand, search = 4, tries = 40): boolean {
    if (this.addProp(c)) return true;
    for (let i = 1; i <= tries; i++) {
      if (this.addProp({ ...c, pos: this.inDisc(c.pos, (search * i) / tries) })) return true;
    }
    return false;
  }

  /** Try candidates from `make` until `count` are placed or tries run out. */
  scatter(count: number, make: () => Cand, maxTries = count * 40): number {
    let placed = 0;
    for (let t = 0; t < maxTries && placed < count; t++) if (this.addProp(make())) placed++;
    return placed;
  }

  private lootFits(p: P2): boolean {
    if (len(p) > LAND_LIMIT - 1) return false;
    for (const c of this.circles) if (dist(p, c) < c.r + LOOT_PROP_CLEARANCE) return false;
    for (const l of this.loot) if (dist(p, l) < LOOT_SPACING) return false;
    return true;
  }

  addLoot(pos: P2, tier: LootTier): boolean {
    const l: LootSpawn = { x: r2(pos.x), z: r2(pos.z), tier };
    if (!this.lootFits(l)) return false;
    this.loot.push(l);
    return true;
  }

  lootNear(pos: P2, tier: LootTier, search = 5, tries = 40): boolean {
    if (this.addLoot(pos, tier)) return true;
    for (let i = 1; i <= tries; i++) {
      if (this.addLoot(this.inDisc(pos, (search * i) / tries), tier)) return true;
    }
    return false;
  }

  lootInDisc(c: P2, radius: number, tiers: LootTier[], triesEach = 80): number {
    let placed = 0;
    for (const tier of tiers) {
      for (let t = 0; t < triesEach; t++) {
        if (this.addLoot(this.inDisc(c, radius), tier)) {
          placed++;
          break;
        }
      }
    }
    return placed;
  }
}

// ---------------------------------------------------------------------------
// Generator
// ---------------------------------------------------------------------------
export function buildIsland(): IslandMapData {
  const b = new Builder(LAYOUT_SEED);
  const anyRot = (): number => b.range(0, Math.PI * 2);

  // 1. Player spawns: 24 on the sand ring, evenly spaced (every 15 deg, ~26 m apart).
  for (let k = 0; k < SPAWN_COUNT; k++) {
    b.addSpawn(polar(SPAWN_START_DEG + k * SPAWN_STEP_DEG, SPAWN_RING_R));
  }

  // 2. Anchor structures first so they always get their spot.
  // Dock (harbour) POI: landward end on the beach, seaward end over water.
  const dock1 = polar(95, 111);
  b.addProp({ kind: 'dock', pos: dock1, rotY: outward(dock1), scale: 1 });
  const dock2 = polar(104, 109);
  b.addProp({ kind: 'dock', pos: dock2, rotY: outward(dock2), scale: 0.75 });

  const boathouse = polar(95, 83);
  b.propNear({ kind: 'hut', pos: boathouse, rotY: outward(boathouse), scale: 1.1 });
  const shed = polar(107, 86);
  b.propNear({ kind: 'hut', pos: shed, rotY: outward(shed), scale: 0.9 });

  // Village: six huts in a ring facing a central plaza.
  const village = poiCentre('village');
  for (let k = 0; k < 6; k++) {
    const p = offset(village, 15 + 60 * k, 13);
    b.propNear({ kind: 'hut', pos: p, rotY: facing(p, village), scale: b.range(1.0, 1.2) }, 3);
  }

  // Tiki bar: one hut facing the sea.
  const bar = polar(195, 89);
  b.propNear({ kind: 'hut', pos: bar, rotY: outward(bar), scale: 1 }, 3);

  // Wreck cove: a big beached hull plus a small overturned rowboat.
  const hull = polar(315, 99);
  b.propNear({ kind: 'boat', pos: hull, rotY: outward(hull) + 1.1, scale: 1.8 }, 3);
  b.propNear({ kind: 'boat', pos: polar(301, 96), rotY: anyRot(), scale: 1 }, 3);

  // 3. POI dressing.
  // Summit: exposed hilltop, a beacon of four torches, a sparse ring of low rocks and crates.
  const summit = poiCentre('summit');
  for (let k = 0; k < 4; k++) {
    b.propNear({ kind: 'tikiTorch', pos: offset(summit, 45 + 90 * k, 3.5), rotY: 0, scale: 1 }, 1.5);
  }
  for (let k = 0; k < 8; k++) {
    const pos = offset(summit, 22.5 + 45 * k + b.range(-8, 8), b.range(10, 14));
    b.propNear({ kind: 'rock', pos, rotY: anyRot(), scale: b.range(0.7, 1.1) }, 3);
  }
  for (let k = 0; k < 4; k++) {
    const pos = offset(summit, 90 * k + b.range(-20, 20), b.range(6, 8));
    b.propNear({ kind: 'crate', pos, rotY: anyRot(), scale: 1 }, 2);
  }
  b.scatter(4, () => ({
    kind: 'bush',
    pos: offset(summit, b.range(0, 360), b.range(9, 21)),
    rotY: anyRot(),
    scale: b.range(0.8, 1.2),
  }));

  // Rocks: a boulder field on the NE shore. Big cover, broken sightlines.
  const rockpoint = poiCentre('rocks');
  b.scatter(
    14,
    () => ({ kind: 'rock', pos: b.inDisc(rockpoint, 18), rotY: anyRot(), scale: b.range(1.0, 2.0) }),
    800,
  );
  b.scatter(4, () => ({ kind: 'bush', pos: b.inDisc(rockpoint, 18), rotY: anyRot(), scale: b.range(0.8, 1.2) }));
  b.scatter(2, () => ({ kind: 'driftwood', pos: b.inDisc(rockpoint, 14), rotY: anyRot(), scale: b.range(0.8, 1.2) }));

  // Harbour: torches flank the main dock, cargo crates on the quay.
  b.propNear({ kind: 'tikiTorch', pos: polar(92, 102.5), rotY: 0, scale: 1 }, 2);
  b.propNear({ kind: 'tikiTorch', pos: polar(98, 102.5), rotY: 0, scale: 1 }, 2);
  b.scatter(10, () => ({ kind: 'crate', pos: b.inDisc(polar(98, 92), 11), rotY: anyRot(), scale: b.range(0.9, 1.2) }));
  b.scatter(2, () => ({ kind: 'driftwood', pos: b.inDisc(polar(86, 100), 6), rotY: anyRot(), scale: b.range(0.8, 1.2) }));

  // Palm grove: dense inland palms and bushes. Close-range jungle fights.
  const grove = poiCentre('grove');
  b.scatter(30, () => ({ kind: 'palm', pos: b.inDisc(grove, 20), rotY: anyRot(), scale: b.range(0.9, 1.35) }), 900);
  b.scatter(12, () => ({ kind: 'bush', pos: b.inDisc(grove, 20), rotY: anyRot(), scale: b.range(0.8, 1.3) }));
  b.scatter(3, () => ({ kind: 'crate', pos: b.inDisc(grove, 8), rotY: anyRot(), scale: 1 }));
  b.scatter(2, () => ({ kind: 'rock', pos: b.inDisc(grove, 18), rotY: anyRot(), scale: b.range(0.8, 1.3) }));

  // Tiki bar: umbrellas on the sand, torches, a few crates by the bar.
  const tiki = poiCentre('tikibar');
  b.scatter(6, () => ({ kind: 'umbrella', pos: polar(b.range(186, 204), b.range(97, 103)), rotY: anyRot(), scale: 1 }));
  b.scatter(6, () => ({ kind: 'tikiTorch', pos: polar(b.range(187, 203), b.range(91, 99)), rotY: 0, scale: 1 }));
  b.scatter(3, () => ({ kind: 'crate', pos: b.inDisc(polar(195, 87), 8), rotY: anyRot(), scale: 1 }));
  b.scatter(3, () => ({ kind: 'bush', pos: b.inDisc(tiki, 14), rotY: anyRot(), scale: b.range(0.8, 1.2) }));

  // Village plaza: torches, crates as plaza cover, some greenery around the huts.
  for (let k = 0; k < 4; k++) {
    b.propNear({ kind: 'tikiTorch', pos: offset(village, 45 + 90 * k, 5), rotY: 0, scale: 1 }, 1.5);
  }
  b.scatter(6, () => ({
    kind: 'crate',
    pos: offset(village, b.range(0, 360), b.range(6, 20)),
    rotY: anyRot(),
    scale: b.range(0.9, 1.1),
  }));
  b.scatter(6, () => ({ kind: 'bush', pos: b.inDisc(village, 24), rotY: anyRot(), scale: b.range(0.8, 1.2) }));
  b.scatter(6, () => ({ kind: 'palm', pos: b.inDisc(village, 24), rotY: anyRot(), scale: b.range(0.9, 1.3) }));

  // Wreck cove: washed-up cargo and driftwood, rocks framing the cove.
  const wreck = poiCentre('wreck');
  b.scatter(8, () => ({ kind: 'driftwood', pos: b.inDisc(polar(310, 97), 14), rotY: anyRot(), scale: b.range(0.8, 1.3) }));
  b.scatter(8, () => ({ kind: 'crate', pos: b.inDisc(wreck, 14), rotY: anyRot(), scale: b.range(0.9, 1.2) }));
  b.scatter(5, () => ({ kind: 'rock', pos: b.inDisc(wreck, 18), rotY: anyRot(), scale: b.range(0.9, 1.6) }));

  // 4. Global dressing.
  // Coastal palm clusters, centred between spawns so each spawn lands on open sand.
  const clusters = 24;
  for (let k = 0; k < clusters; k++) {
    const c = polar(k * (360 / clusters) + b.range(-4, 4), b.range(93, 101));
    const n = b.rng() < 0.5 ? 3 : 4;
    b.scatter(n, () => ({ kind: 'palm', pos: b.inDisc(c, 6), rotY: anyRot(), scale: b.range(0.85, 1.3) }), n * 15);
  }
  // Inland jungle: palms, bushes and rocks between POIs.
  b.scatter(20, () => ({ kind: 'palm', pos: b.inRing(18, 88), rotY: anyRot(), scale: b.range(0.9, 1.3) }));
  b.scatter(45, () => ({ kind: 'bush', pos: b.inRing(8, 92), rotY: anyRot(), scale: b.range(0.7, 1.3) }));
  b.scatter(22, () => ({ kind: 'rock', pos: b.inRing(14, 90), rotY: anyRot(), scale: b.range(0.6, 1.4) }));
  // Beach clutter: driftwood, umbrellas, small rocks.
  b.scatter(12, () => ({ kind: 'driftwood', pos: b.inRing(96, 103), rotY: anyRot(), scale: b.range(0.8, 1.3) }));
  b.scatter(8, () => ({ kind: 'umbrella', pos: b.inRing(94, 102), rotY: anyRot(), scale: 1 }));
  b.scatter(8, () => ({ kind: 'rock', pos: b.inRing(94, 102), rotY: anyRot(), scale: b.range(0.5, 0.9) }));

  // 5. Loot (target ~77: ~51 common / ~19 rare / 7 epic).
  // Beach ring commons in the gaps between spawns. Gaps alternate 2 points / 1 point, so every
  // spawn borders one of each = 3 loot points 13-16 m away (<= ~21 m after nudges and 3 m spawn jitter).
  for (let k = 0; k < SPAWN_COUNT; k++) {
    const gapDeg = SPAWN_START_DEG + (k + 0.5) * SPAWN_STEP_DEG;
    b.lootNear(polar(gapDeg, 97), 'common');
    if (k % 2 === 0) b.lootNear(polar(gapDeg, 90), 'common');
  }
  // POI caches: all epic loot lives here (summit + grove only).
  for (const d of POI_DEFS) {
    b.lootInDisc(poiCentre(d.id), d.radius * 0.9, tierList(d.loot));
  }
  // A few inland pickups between POIs to reward rotating through the jungle.
  let inland = 0;
  for (let t = 0; t < 4000 && inland < INLAND_LOOT; t++) {
    const p = b.inRing(15, 86);
    if (POI_DEFS.some((d) => dist(p, poiCentre(d.id)) < d.radius)) continue;
    if (b.addLoot(p, inland < INLAND_RARE ? 'rare' : 'common')) inland++;
  }

  return {
    kind: 'island',
    id: 'island01',
    nameKey: 'map.island01.name',
    carrier: 'seaplane',
    islandRadius: ISLAND_RADIUS,
    worldRadius: WORLD_RADIUS,
    baseHeight: BASE_HEIGHT,
    beachWidth: BEACH_WIDTH,
    shoreNoise: { ...SHORE_NOISE },
    hills: HILL_DEFS.map((h) => {
      const c = polar(h.deg, h.r);
      return { x: r2(c.x), z: r2(c.z), radius: h.radius, height: h.height };
    }),
    props: b.props,
    playerSpawns: b.spawns,
    lootSpawns: b.loot,
    zoneCenters: ZONE_CENTER_DEFS.map(([deg, r]) => {
      const c = polar(deg, r);
      return { x: r2(c.x), z: r2(c.z) };
    }),
    pois: POI_DEFS.map((d) => {
      const c = polar(d.deg, d.r);
      return { id: d.id, nameKey: `poi.${d.id}`, x: r2(c.x), z: r2(c.z), radius: d.radius };
    }),
  };
}

export const ISLAND: IslandMapData = buildIsland();
